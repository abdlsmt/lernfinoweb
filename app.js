function detectInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const qLang = params.get("lang");
    if (qLang && I18N[qLang.toLowerCase()]) return qLang.toLowerCase();
  } catch {}
  const saved = localStorage.getItem("lernfino_web_lang");
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || "tr").toLowerCase();
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("en")) return "en";
  return "tr";
}

function stopAudio() {
  if (currentAudioPlayer) {
    currentAudioPlayer.pause();
    currentAudioPlayer.currentTime = 0;
    currentAudioPlayer = null;
  }
}

function playAudioFile(srcPath, fallbackWord) {
  stopAudio();
  if (srcPath) {
    const audio = new Audio(srcPath);
    currentAudioPlayer = audio;
    audio.play().catch(() => {
      if (fallbackWord) speakGermanSynthesis(fallbackWord);
    });
  } else if (fallbackWord) {
    speakGermanSynthesis(fallbackWord);
  }
}

function speakGermanSynthesis(text) {
  if (!("speechSynthesis" in window)) return;
  try {
    window.speechSynthesis.cancel();
    const utter = new SpeechSynthesisUtterance(text);
    utter.lang = "de-DE";
    utter.rate = 0.94;
    window.speechSynthesis.speak(utter);
  } catch {
    // Ignore speech synthesis errors
  }
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem("lernfino_web_lang", lang);
  document.documentElement.lang = lang;
  document.title = I18N[lang].pageTitle;

  // Update all [data-i18n] text
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[lang][key];
    if (val !== undefined) {
      el.innerHTML = val;
    }
  });

  // Update input placeholder
  const emailInput = document.getElementById("emailInput");
  if (emailInput) {
    emailInput.placeholder = I18N[lang]["launch.emailPlaceholder"];
  }

  // Update select options (Fix for dropdown options not translating)
  const levelSelect = document.getElementById("levelSelect");
  if (levelSelect) {
    const optMap = {
      A1: I18N[lang]["launch.optA1"],
      A2: I18N[lang]["launch.optA2"],
      B1: I18N[lang]["launch.optB1"],
      B2: I18N[lang]["launch.optB2"]
    };
    Array.from(levelSelect.options).forEach((opt) => {
      if (optMap[opt.value]) {
        opt.textContent = optMap[opt.value];
      }
    });
  }

  // Update language button active states
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  renderDemoStage();
  renderDictionaryCard();
}

function renderDemoStage() {
  const levelData = DEMO_LEVELS[currentLevel];
  const storyTitleEl = document.getElementById("demoStoryTitle");
  const badgeEl = document.getElementById("demoLevelBadge");
  const sentenceEl = document.getElementById("demoGermanSentence");
  const transEl = document.getElementById("demoSentenceTranslation");

  if (storyTitleEl) storyTitleEl.textContent = levelData.storyTitle;
  if (badgeEl) badgeEl.textContent = levelData.badge[currentLang];
  if (transEl) transEl.textContent = levelData.translation[currentLang];

  if (sentenceEl) {
    sentenceEl.innerHTML = "";
    levelData.words.forEach((tok) => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "interactive-word" + (tok.key === currentWordKey ? " selected" : "");
      btn.textContent = tok.label;
      btn.addEventListener("click", () => {
        currentWordKey = tok.key;
        renderDemoStage();
        renderDictionaryCard();

        const entry = WORD_DICTIONARY[currentWordKey];
        if (entry) {
          playAudioFile(entry.audioFile, entry.headword);
        }
      });
      sentenceEl.appendChild(btn);
      sentenceEl.appendChild(document.createTextNode(" "));
    });
  }
}

function renderDictionaryCard() {
  const entry = WORD_DICTIONARY[currentWordKey] || WORD_DICTIONARY.hinter;
  document.getElementById("dictArticle").textContent = entry.article[currentLang];
  document.getElementById("dictHeadword").textContent = entry.headword;
  document.getElementById("dictMeaning").textContent = entry.meaning[currentLang];
  document.getElementById("dictGrammarNote").textContent = entry.grammar[currentLang];
  document.getElementById("dictExampleDe").textContent = entry.exampleDe;
  document.getElementById("dictExampleTr").textContent = entry.exampleTr[currentLang];
  document.getElementById("dictWordAudioLabel").textContent = I18N[currentLang]["demo.listenWord"];

  const saveBtn = document.getElementById("saveWordBtn");
  const saveIcon = document.getElementById("saveWordIcon");
  const saveText = document.getElementById("saveWordText");
  const isSaved = savedWords.has(currentWordKey);

  if (saveBtn && saveIcon && saveText) {
    saveIcon.textContent = isSaved ? "" : "＋";
    saveText.textContent = isSaved ? I18N[currentLang]["demo.savedBtn"] : I18N[currentLang]["demo.saveBtn"];
  }
}

document.addEventListener("DOMContentLoaded", () => {
  // Initialize Theme
  const savedTheme = localStorage.getItem("lernfino_web_theme");
  if (savedTheme === "dark" || savedTheme === "light") {
    document.documentElement.setAttribute("data-theme", savedTheme);
  }

  const themeToggle = document.getElementById("themeToggle");
  if (themeToggle) {
    themeToggle.addEventListener("click", () => {
      const current = document.documentElement.getAttribute("data-theme") || "light";
      const next = current === "light" ? "dark" : "light";
      document.documentElement.setAttribute("data-theme", next);
      localStorage.setItem("lernfino_web_theme", next);
    });
  }

  // Language buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang");
      if (lang) setLanguage(lang);
    });
  });

  document.querySelectorAll("[data-lang-switch]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang-switch");
      if (lang) {
        setLanguage(lang);
        window.scrollTo({ top: 0, behavior: "smooth" });
      }
    });
  });

  // CEFR Level Switcher
  document.querySelectorAll(".cefr-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lvl = btn.getAttribute("data-level");
      if (!lvl || !DEMO_LEVELS[lvl]) return;
      currentLevel = lvl;
      currentWordKey = DEMO_LEVELS[lvl].words[0].key;

      document.querySelectorAll(".cefr-btn").forEach((b) => {
        b.classList.toggle("active", b.getAttribute("data-level") === lvl);
      });

      renderDemoStage();
      renderDictionaryCard();
    });
  });

  // Speak Sentence (Plays real studio book audio!)
  const speakSentenceBtn = document.getElementById("speakSentenceBtn");
  if (speakSentenceBtn) {
    speakSentenceBtn.addEventListener("click", () => {
      const audioPath = DEMO_LEVELS[currentLevel].audioFile;
      playAudioFile(audioPath, null);
    });
  }

  // Speak Word (Plays real studio dictionary audio!)
  const speakWordBtn = document.getElementById("speakWordBtn");
  if (speakWordBtn) {
    speakWordBtn.addEventListener("click", () => {
      const entry = WORD_DICTIONARY[currentWordKey];
      if (entry) {
        playAudioFile(entry.audioFile, entry.headword);
      }
    });
  }

  // Save Word (SRS Simulation)
  const saveWordBtn = document.getElementById("saveWordBtn");
  if (saveWordBtn) {
    saveWordBtn.addEventListener("click", () => {
      if (savedWords.has(currentWordKey)) {
        savedWords.delete(currentWordKey);
      } else {
        savedWords.add(currentWordKey);
      }
      renderDictionaryCard();
    });
  }

  // Early Access Notification Form (Fix: Hidden until submit!)
  const notifyForm = document.getElementById("notifyForm");
  const emailInput = document.getElementById("emailInput");
  const levelSelect = document.getElementById("levelSelect");
  const formFeedback = document.getElementById("formFeedback");
  const feedbackMessage = document.getElementById("feedbackMessage");

  if (notifyForm && emailInput && formFeedback) {
    notifyForm.addEventListener("submit", (e) => {
      e.preventDefault();
      const email = emailInput.value.trim();
      const level = levelSelect ? levelSelect.value : "B1";
      if (!email) return;

      const list = JSON.parse(localStorage.getItem("lernfino_waitlist") || "[]");
      list.push({ email, level, lang: currentLang, date: new Date().toISOString() });
      localStorage.setItem("lernfino_waitlist", JSON.stringify(list));

      // Reveal only on successful submit!
      formFeedback.style.display = "flex";
      formFeedback.classList.add("is-visible");
      formFeedback.removeAttribute("hidden");

      const msg = I18N[currentLang]["launch.successMsg"].replace("{email}", email);
      if (feedbackMessage) {
        feedbackMessage.textContent = msg;
      } else {
        formFeedback.textContent = msg;
      }
      emailInput.value = "";
    });
  }

  // Initial render
  setLanguage(detectInitialLang());
});
