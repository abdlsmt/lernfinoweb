let legalCurrentLang = "tr";

function scrollToWaitlistPrivacy() {
  if (!/^#waitlist-privacy(?:-(?:tr|en|de))?$/.test(window.location.hash)) return;
  requestAnimationFrame(() => {
    document.getElementById("waitlist-privacy-" + legalCurrentLang)?.scrollIntoView({ block: "start", behavior: "instant" });
  });
}

function detectLegalLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const qLang = params.get("lang");
    if (qLang && (LEGAL_I18N[qLang.toLowerCase()] || LEGAL_NOTE_LANGS[qLang.toLowerCase()])) {
      return qLang.toLowerCase();
    }
  } catch {}

  const saved = localStorage.getItem("lernfino_web_lang");
  if (saved && (LEGAL_I18N[saved] || LEGAL_NOTE_LANGS[saved])) return saved;

  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("tr")) return "tr";
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("en")) return "en";
  return "en";
}

function setLegalLanguage(chosen) {
  const isNote = !LEGAL_I18N[chosen] && !!LEGAL_NOTE_LANGS[chosen];
  if (!LEGAL_I18N[chosen] && !isNote) return;
  const lang = isNote ? "en" : chosen;
  legalCurrentLang = lang;
  localStorage.setItem("lernfino_web_lang", chosen);
  document.documentElement.lang = chosen;
  // Body stays English (ltr) for note languages; only the note box gets rtl for Arabic
  document.documentElement.dir = "ltr";

  // Binding-language note for the 12 additional languages
  const oldNote = document.getElementById("legalLangNote");
  if (oldNote) oldNote.remove();
  if (isNote) {
    const host = document.querySelector(".legal-card") || document.querySelector(".legal-main");
    if (host) {
      const note = document.createElement("div");
      note.id = "legalLangNote";
      note.className = "callout-box callout-amber";
      note.lang = chosen;
      note.dir = chosen === "ar" ? "rtl" : "ltr";
      note.textContent = LEGAL_NOTE_LANGS[chosen];
      host.insertBefore(note, host.firstChild);
    }
  }
  // Translated error-reports paragraph (only exists on /privacy)
  const errPara = document.getElementById("errorReportsPara");
  if (errPara) {
    if (!errPara.dataset.en) errPara.dataset.en = errPara.innerHTML;
    if (isNote && ERROR_REPORTS_LANGS[chosen]) {
      errPara.innerHTML = ERROR_REPORTS_LANGS[chosen];
      errPara.lang = chosen;
      errPara.dir = chosen === "ar" ? "rtl" : "ltr";
    } else {
      errPara.innerHTML = errPara.dataset.en;
      errPara.removeAttribute("lang");
      errPara.removeAttribute("dir");
    }
  }
  const hosting = document.getElementById("hostingDisclosureEn");
  if (hosting) {
    hosting.dataset.en ??= hosting.textContent;
    hosting.textContent = HOSTING_DISCLOSURES[chosen] ?? hosting.dataset.en;
    hosting.lang = isNote ? chosen : "en";
    hosting.dir = chosen === "ar" ? "rtl" : "ltr";
  }
  const sel = document.getElementById("langSelect");
  if (sel) sel.value = chosen;

  // 1. Update text elements with [data-i18n]
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = LEGAL_I18N[lang][key];
    if (val !== undefined) {
      el.innerHTML = val;
    }
  });

  // 2. Toggle active language buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === chosen;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  // 3. Show/hide language-specific content blocks: [data-lang-content="tr|en|de"]
  document.querySelectorAll("[data-lang-content]").forEach((block) => {
    const targetLang = block.getAttribute("data-lang-content");
    if (targetLang === lang) {
      block.style.display = "";
    } else {
      block.style.display = "none";
    }
  });

  scrollToWaitlistPrivacy();

  // 4. Update dynamic email builder if present on /delete-account
  updateDeleteMailto();
}

