let legalCurrentLang = "tr";

function detectLegalLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const qLang = params.get("lang");
    if (qLang && LEGAL_I18N[qLang.toLowerCase()]) {
      return qLang.toLowerCase();
    }
  } catch {}

  const saved = localStorage.getItem("lernfino_web_lang");
  if (saved && LEGAL_I18N[saved]) return saved;

  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("tr")) return "tr";
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("en")) return "en";
  return "en";
}

function setLegalLanguage(lang) {
  if (!LEGAL_I18N[lang]) return;
  legalCurrentLang = lang;
  localStorage.setItem("lernfino_web_lang", lang);
  document.documentElement.lang = lang;

  // 1. Update text elements with [data-i18n]
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = LEGAL_I18N[lang][key];
    if (val !== undefined) {
      el.innerHTML = val;
    }
  });

  // 2. Toggle active language buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  // 3. Show/hide language-specific content blocks: [data-lang-content="tr|en|de"]
  document.querySelectorAll("[data-lang-content]").forEach((block) => {
    const targetLang = block.getAttribute("data-lang-content");
    if (targetLang === lang) {
      block.style.display = "";
    } else {
      block.style.display = "none";
    }
  });

  // 4. Update dynamic email builder if present on /delete-account
  updateDeleteMailto();
}

function updateDeleteMailto() {
  const emailInput = document.getElementById("deleteEmailInput");
  const actionBtn = document.getElementById("sendDeleteEmailBtn");
  if (!actionBtn) return;

  const enteredEmail = emailInput ? emailInput.value.trim() : "";
  let subject = "";
  let body = "";

  if (legalCurrentLang === "en") {
    subject = encodeURIComponent("Lernfino Account & Data Deletion Request");
    body = encodeURIComponent(
      `Hello Lernfino Support Team,\n\nI would like to permanently delete my Lernfino account and all associated cloud data.\n\nRegistered Email: ${enteredEmail || "[Enter your email]"}\n\nPlease confirm once the deletion is completed.\n\nThank you.`
    );
  } else if (legalCurrentLang === "de") {
    subject = encodeURIComponent("Lernfino Konto- und Datenlöschung");
    body = encodeURIComponent(
      `Hallo Lernfino Support-Team,\n\nich möchte mein Lernfino-Konto und alle zugehörigen Daten dauerhaft löschen.\n\nRegistrierte E-Mail-Adresse: ${enteredEmail || "[Ihre E-Mail-Adresse]"}\n\nBitte bestätigen Sie die Löschung.\n\nVielen Dank.`
    );
  } else {
    subject = encodeURIComponent("Lernfino Hesap ve Veri Silme Talebi");
    body = encodeURIComponent(
      `Merhaba Lernfino Destek Ekibi,\n\nLernfino hesabımı, bulut yedeklerimi ve sunucularınızdaki tüm kişisel verilerimi kalıcı olarak silmek istiyorum.\n\nKayıtlı E-posta Adresim: ${enteredEmail || "[Kayıtlı e-postanızı buraya yazın]"}\n\nİşlem tamamlandığında lütfen tarafıma bilgi veriniz.\n\nTeşekkürler.`
    );
  }

  actionBtn.href = `mailto:support@lernfino.com?subject=${subject}&body=${body}`;
}

document.addEventListener("DOMContentLoaded", () => {
  // 1. Theme Initialization
  const savedTheme = localStorage.getItem("lernfino_web_theme");
  if (savedTheme === "dark" || savedTheme === "light") {
    document.documentElement.setAttribute("data-theme", savedTheme);
  }

  const themeToggle = document.getElementById("themeToggle");
  if (themeToggle) {
    themeToggle.addEventListener("click", () => {
      const current = document.documentElement.getAttribute("data-theme") || "light";
      const next = current === "dark" ? "light" : "dark";
      document.documentElement.setAttribute("data-theme", next);
      localStorage.setItem("lernfino_web_theme", next);
    });
  }

  // 2. Language Switcher Buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const targetLang = btn.getAttribute("data-lang");
      if (targetLang) {
        setLegalLanguage(targetLang);
      }
    });
  });

  // Footer language links
  document.querySelectorAll("[data-lang-switch]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const targetLang = btn.getAttribute("data-lang-switch");
      if (targetLang) {
        setLegalLanguage(targetLang);
      }
    });
  });

  // 3. FAQ Accordion Click Handlers
  document.querySelectorAll(".faq-question").forEach((btn) => {
    btn.addEventListener("click", () => {
      const item = btn.closest(".faq-item");
      if (!item) return;
      const isOpen = item.classList.contains("open");

      // Optional: Close others in same list
      const parentList = item.closest(".faq-list");
      if (parentList) {
        parentList.querySelectorAll(".faq-item").forEach((it) => it.classList.remove("open"));
      }

      if (!isOpen) {
        item.classList.add("open");
      }
    });
  });

  // 4. Interactive Deletion Email Builder
  const deleteEmailInput = document.getElementById("deleteEmailInput");
  if (deleteEmailInput) {
    deleteEmailInput.addEventListener("input", updateDeleteMailto);
  }

  // 5. Initial language render
  setLegalLanguage(detectLegalLang());
});
